// Generates src/engine.generated.js: Tara's real scoring engine
// (computeV99Posterior and every top-level helper it reaches), pulled out of
// src/App.jsx with the same AST walk tests/helpers/scoreEngineHarness.js uses.
// Nothing is copied by hand, so the probe measures the code the site runs.
//
// Run from the repo root after `npm ci`:  node server/probe-cf/scripts/build-engine.mjs
// The output is committed because Cloudflare builds this Worker from the
// server/probe-cf folder alone.
import {readFileSync, writeFileSync, mkdirSync, copyFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';
import {parse} from '@babel/parser';
import traverseModule from '@babel/traverse';

const traverse = traverseModule.default || traverseModule;
const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..', '..');
const out = join(here, '..', 'src');
const app = readFileSync(join(repo, 'src', 'App.jsx'), 'utf8');

// Same external set the test harness injects; these live in src/*.js modules.
const VENDOR = ['forecastTiming.js', 'marketDataQuality.js', 'economicCalendar.js', 'learningCore.js',
  'decisionAuthority.js', 'callIntegrity.js', 'callPolicy.js'];
const forecastExports = Object.keys(await import(new URL(`file://${join(repo, 'src', 'forecastTiming.js').replace(/\\/g, '/')}`)));
const external = new Set([...forecastExports, 'observedFundingPair', 'dampenScore', 'directionFeatures', 'canonicalRegimeFlags']);
const builtins = new Set(['Array', 'Object', 'Number', 'String', 'Math', 'Set', 'Map', 'JSON', 'Boolean', 'Date', 'console', 'Intl',
  'parseFloat', 'parseInt', 'isNaN', 'Infinity', 'NaN', 'undefined', 'window', 'localStorage']);

const ast = parse(app, {sourceType: 'module', plugins: ['jsx']});
const declarations = new Map();
for (const statement of ast.program.body) {
  if (statement.type === 'VariableDeclaration') for (const d of statement.declarations) {
    if (d.id.type === 'Identifier' && d.init) declarations.set(d.id.name, `const ${d.id.name}=${app.slice(d.init.start, d.init.end)};`);
  }
  if (statement.type === 'FunctionDeclaration') declarations.set(statement.id.name, app.slice(statement.start, statement.end));
}
const ordered = [], selected = new Set();
function select(name) {
  if (selected.has(name) || external.has(name) || builtins.has(name)) return;
  const code = declarations.get(name);
  if (!code) throw new Error(`Missing scoring dependency: ${name}`);
  selected.add(name);
  traverse(parse(code, {sourceType: 'script'}), {ReferencedIdentifier(p) { if (!p.scope.hasBinding(p.node.name, true)) select(p.node.name); }});
  ordered.push(code);
}
select('computeV99Posterior');
select('computeFGT');

mkdirSync(join(out, 'vendor'), {recursive: true});
for (const f of VENDOR) copyFileSync(join(repo, 'src', f), join(out, 'vendor', f));
const header = `// GENERATED by server/probe-cf/scripts/build-engine.mjs from src/App.jsx. Do not edit.
// ${ordered.length} declarations, extracted ${new Date().toISOString()}.
import * as forecasts from './vendor/forecastTiming.js';
import {observedFundingPair} from './vendor/marketDataQuality.js';
import {dampenScore} from './vendor/economicCalendar.js';
import {directionFeatures} from './vendor/learningCore.js';
import {canonicalRegimeFlags} from './vendor/decisionAuthority.js';
const {${forecastExports.join(',')}} = forecasts;
// The engine reads these browser globals defensively; on a server they are empty.
const window = {};
const localStorage = {getItem: () => null, setItem() {}, removeItem() {}};
`;
writeFileSync(join(out, 'engine.generated.js'), `${header}\n${ordered.join('\n')}\n\nexport {computeV99Posterior, computeFGT};\n`);
console.log(`engine.generated.js: ${ordered.length} declarations, ${VENDOR.length} vendor modules`);
